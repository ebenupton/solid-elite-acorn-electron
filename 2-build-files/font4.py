#!/usr/bin/env python3
"""font4.py: the 4 x 8 font of the Electron's MODE 5 screen (docs/renderer.md,
"The text").

    python3 2-build-files/font4.py [PNG]

The game prints 32 columns across the space view's 128 MODE 5 pixels, so a
character cell is one byte wide: four pixels (each two of the original's
pixels wide, so a cell is as wide on the screen as the original's) and eight
rows high. The glyphs below are drawn for that cell by hand, after the
Electron's MOS font (characters 32 to 127, &C000 in its ROM): three pixels
wide in the cell's first three columns (the fourth is the gap to the next
character), capitals and figures on rows 0 to 6, the lower case's x-height
on rows 2 to 6 and its descenders on row 7, as the MOS font has them.

Writes 1-source-files/main-sources/gfx-font.asm (F_FONT, which bank 6's
gfx-bank6.asm INCLUDEs: the font's one copy, which the frame layer's text
map and the game's direct-mode text both draw from, through f_glyph and
F_DCHAR in gfx-frame.asm) and, with an argument, a preview PNG of the
character set at 4x (each MODE 5 pixel 8 x 4 screen pixels: two game pixels
wide, one row high, at the screen's aspect).

The table packs a glyph into four bytes, two rows a byte (row 2k in the
high nibble, row 2k + 1 in the low one), a nibble's bit 3 the leftmost
pixel: f_nib (gfx-frame.asm) turns a nibble n into the MODE 5 byte of those
pixels in logical colour 3, n * &11.
"""
