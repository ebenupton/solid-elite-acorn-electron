def rows(c):
    """the glyph of character c: eight 4-bit rows (bit 3 the leftmost pixel)"""
    g = GLYPHS[c] + ['...'] * (8 - len(GLYPHS[c]))
    assert len(g) == 8 and all(len(r) == 3 and set(r) <= {'#', '.'} for r in g), c
    return [sum(8 >> i for i, p in enumerate(r) if p == '#') for r in g]


def main():
    chars = [chr(c) for c in range(32, 128)]
    assert set(GLYPHS) == set(chars)
    lines = ['\\ gfx-font.asm -- written by 2-build-files/font4.py; do not edit.', '\\',
             '\\ F_FONT: the 4 x 8 font, characters 32 to 127, four bytes each: rows 2k',
             '\\ and 2k + 1 in the high and low nibbles of byte k, bit 3 of a nibble the',
             '\\ leftmost pixel (f_nib makes the MODE 5 byte). Its only copy: the frame',
             "\\ layer's text and the game's direct-mode text both draw from it.", '',
             '.F_FONT']
    for c in chars:
        r = rows(c)
        b = [(r[2 * k] << 4) | r[2 * k + 1] for k in range(4)]
        name = {' ': 'space', '\x7f': 'DEL', '\\': 'backslash'}.get(c, c)
        lines.append(' EQUB &%02X, &%02X, &%02X, &%02X   \\ %s' % (*b, name))
    open(OUT, 'w').write('\n'.join(lines) + '\n')
    print('font4: %d glyphs, %d bytes -> %s' % (len(chars), 4 * len(chars), os.path.relpath(OUT, ROOT)))
    if len(sys.argv) > 1:
        from PIL import Image
        cols, sx, sy = 16, 8, 4                   # a MODE 5 pixel: 8 x 4 at 4x
        im = Image.new('RGB', (cols * 4 * sx + 2 * sx, 6 * 8 * sy + 2 * sy), (0, 0, 0))
        px = im.load()
        for i, c in enumerate(chars):
            r = rows(c)
            ox, oy = sx + (i % cols) * 4 * sx, sy + (i // cols) * 8 * sy
            for y in range(8):
                for x in range(4):
                    if r[y] & (8 >> x):
                        for dy in range(sy):
                            for dx in range(sx):
                                px[ox + x * sx + dx, oy + y * sy + dy] = (255, 255, 0)
        im.save(sys.argv[1])
        print('font4: preview', sys.argv[1])


if __name__ == '__main__':
    main()
