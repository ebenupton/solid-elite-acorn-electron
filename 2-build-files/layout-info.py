#!/usr/bin/env python3
#
# ******************************************************************************
#
# BBC MICRO DISC ELITE (MODEL B PORT) LAYOUT INFORMATION SCRIPT
#
# Run by the Makefile from the repository's root, after the loader has been
# assembled and before the programs are. From the loader's symbols
# (3-assembled-output/loader-symbols.txt, which "beebasm -d" writes) it
# produces 3-assembled-output/resident.asm: the addresses in the loader's
# resident block A (elite-resident.asm, main RAM &0400-&07FF) that the
# programs call or read, which the layout files (elite-layout-flight.asm,
# elite-layout-docked.asm) INCLUDE:
#
#   * the far calls between a program's home and cold banks (farC, farCj,
#     farH, farHj) and the bank numbers the loader found (BANK4, BANK7,
#     BANK5, BANK6);
#
#   * PCLI, the game's OSCLI (OSCLI = PCLI in the programs' sources)
#
#   * IRQG, the game's interrupt handler, and NA% (the last saved
#     commander), CHK2, CHK and BRBR1 (the break handler), which were the
#     original's block B at &1100
#
#   * PANR, and pcb_o and pis_t, the circle engine's tables, which the
#     flight code's pc_circ reads
#
# It also writes 3-assembled-output/flight-banks.txt and docked-banks.txt,
# the bank of each label of each program, for the harness (below).
#
# (docs/memory-map.md)
#
# ******************************************************************************

import re

OUT = "3-assembled-output/"
WINDOW7 = {"flight": ("gfx-raster_disc-bank7.asm", "gfx-raster_disc2-bank7.asm",
                      "gfx-raster_dpatch-bank7.asm", "gfx-frame-bank7.asm", "gfx-merid-bank7.asm",
                      "gfx-glue-bank7.asm")}   # (bank 7's renderer window, the renderer's
                                                        # bank 7 passes: elite-layout-flight.asm)
NAMES = ("farC", "farCj", "farH", "farHj", "farC6", "farC6j", "BANK4", "BANK7", "BANK5", "BANK6", "PCLI",
         "IRQG", "NA%", "CHK2", "CHK", "BRBR1", "PANR", "dfsin", "dfsout", "pload",
         "pcb_o", "pis_t", "SREQ")   # (SREQ: the sound engine's queue)

sy = {}
for m in re.finditer(r"'([^']+)':(\d+)", open(OUT + "loader-symbols.txt").read()):
    sy.setdefault(m.group(1), int(m.group(2)))

with open(OUT + "resident.asm", "w") as f:
    f.write("\\ Generated by 2-build-files/layout-info.py from the loader's symbols:\n")
    f.write("\\ the loader's resident block A (elite-resident.asm)\n\n")
    for n in NAMES:
        f.write(" %s = &%04X\n" % (n, sy[n]))


# The banks of the programs' labels, for the harness (6-harness/blib.mjs):
# 3-assembled-output/<program>-banks.txt, "label C" for each label assembled
# in the program's cold pass, bank 7 (its cold copy and the text tokens),
# "label H" for each label of its hot side's copies (the low pass, the hot
# pass and the blueprints: those in bank 4 have addresses &8000-&BFFF, and
# those in main RAM, which the harness tells by address, are below)


def labels(path):
    """the labels a copy defines, with those of the files it INCLUDEs from
    1-source-files/main-sources (none now: the cold bank's renderer window is
    its bank 7 passes)"""
    try:
        t = open(path, encoding="latin-1").read()
    except FileNotFoundError:          # (before streams.py's place: run again after it)
        return []
    out = re.findall(r"^\s*\.([A-Za-z_][\w%]*)", t, re.M)
    for inc in re.findall(r'^\s*INCLUDE\s+"(1-source-files/main-sources/[^"]+)"', t, re.M):
        out += labels(inc)
    return out


for prog in ("flight", "docked"):
    with open(OUT + "%s-banks.txt" % prog, "w") as f:
        for name in labels(OUT + "elite-%s-cold.asm" % prog) + \
                (labels(OUT + "elite-tokens-cold.asm") if prog != "flight" else []) + \
                sum((labels(OUT + "elite-%s-ovl%d.asm" % (prog, n)) for n in (1, 2, 3)), []) + \
                sum((labels(OUT + w) for w in WINDOW7.get(prog, ())), []):
            f.write("%s C\n" % name)
        for name in sum((labels(OUT + "elite-%s-%s.asm" % (prog, c)) for c in ("low", "hot", "hotm", "hotx", "hotl", "hots", "blueprints")), []):
            f.write("%s H\n" % name)
        for name in labels(OUT + "elite-%s-c6.asm" % prog) + \
                (labels(OUT + "elite-tokens-cold.asm") if prog == "flight" else []):   # (the flight
            f.write("%s 6\n" % name)              # code's cold 6 pass, in bank 6, with its tokens)


# Port: the painter's code in bank 7's renderer window (elite-layout-flight.asm)
# is padded so that each SAMEPAGE pair in it (the ways back that pe's return
# patches in its low byte only: gfx-raster_disc.asm, PEGO) lies in one page.
# The measure (elite-measure-flight.asm) assembles the painter's pass from W7P%:
# its labels give the pairs' offsets from there, and so, for each place in a
# page the pass may start at in the layout, the pad it needs.
# 3-assembled-output/win7pad.asm skips that pad, from W7PB% (the pass's place
# without it); before the measure has run, none

def win7pads():
    try:
        ms = {}
        for m in re.finditer(r"'([^']+)':(\d+)", open(OUT + "measure-flight-symbols.txt").read()):
            ms.setdefault(m.group(1), int(m.group(2)))
        pairs = [(ms[a] - ms["W7P%"], ms[b] - ms["W7P%"]) for a, b in
                 re.findall(r"^\s*SAMEPAGE\s+(\w+)\s*,\s*(\w+)",
                            open(OUT + "gfx-raster_disc-bank7.asm", encoding="latin-1").read(), re.M)]
    except (FileNotFoundError, KeyError):
        return {}
    pads = {}
    for x in range(256):
        k = next((k for k in range(256) if all((x + k + a) >> 8 == (x + k + b) >> 8 for a, b in pairs)), None)
        if k is None:
            raise SystemExit("layout-info.py: no pad puts each SAMEPAGE pair of the painter in one page")
        pads[x] = k
    return pads

with open(OUT + "win7pad.asm", "w") as f:
    f.write("\\ Generated by 2-build-files/layout-info.py: the pad before the painter's\n")
    f.write("\\ pass in bank 7's window, by where in a page it would start\n\n W7PB% = P%\n")
    for x, k in sorted(win7pads().items()):
        if k:
            f.write(" IF LO(W7PB%%) = &%02X : SKIP %d : ENDIF\n" % (x, k))
