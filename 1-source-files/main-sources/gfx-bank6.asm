\ ******************************************************************************
\
\ gfx-bank6.asm - bank 6: the filled renderer's frame layer (docs/renderer.md)
\
\ Port (Model B): the BBC Master port's bank 6 (its elite-gfx.asm's), laid out
\ for the Model B, assembled by 2-build-files/bank6.py once the flight program
\ is (it reads the game's addresses from the flight program's symbols, and
\ the banks' from the loader's, into 3-assembled-output/bank6-game.asm):
\
\   &8000        the frame layer (gfx-frame.asm), the lens flare (gfx-flare.asm),
\                the hangar (gfx-hangar.asm), the bookkeeping
\                for the screens drawn directly (gfx-frame_cold.asm), F_INIT
\                (gfx-finit.asm), then the ships' faces and the lighting's
\                ramps (gfx-faces.asm, gfx-light6.asm, generated by
\                2-build-files/faces.py; the lighting itself, gfx-light.asm,
\                and the faces' normals, gfx-normals.asm, are in the game's
\                bank 4, with the quarter squares)
\   then         the state: the ship records (F_RP, F_SR), the text map (F_TM,
\                F_TMR), the discs' half-widths (F_HW, F_HW2, page aligned),
\                the zero page F_FRAME keeps (f_zsv), the docking slot (F_SLV)
\   FJT% (&BFC0) the entries, a table of jumps: GCALL (the common block's,
\                elite-common.asm) calls the one whose low byte is in X
\                (FG_*, elite-map.asm)
\
\ The common block (COMMON% to COMMON_END%: the code that pages the banks,
\ the same bytes at the same address in every bank, taken in here from bank
\ 5's assembly, COMMON.bin) is just below the page-aligned state. F_INIT,
\ which runs once, is assembled in the room of the sun's half-widths (F_HW2),
\ which are first written after it; the frame layer's calls out of the bank
\ (gfx-glue.asm) are with its code, in the room after the state and in the
\ room after FJT%.
\
\ It also assembles the circle engine's table in main RAM (gfx-merid.asm's
\ main pass) at GLUE%, as the resident block includes it, and writes it to
\ GLUE.bin for the test (6-harness/test_frame.py).
\
\ Each file is placed by its passes (2-build-files/streams.py: every block's
\ "Area:" line names its place): this file INCLUDEs the bank 6 passes
\ (3-assembled-output/<file>-bank6.asm), which bank6.py has streams.py write
\ first.
\
\ ******************************************************************************

 INCLUDE "1-source-files/main-sources/elite-build-options.asm"
 INCLUDE "1-source-files/main-sources/elite-map.asm"
 INCLUDE "3-assembled-output/bank6-game.asm"
 INCLUDE "1-source-files/main-sources/gfx-rws.asm"
 INCLUDE "3-assembled-output/common-entry.asm"   \ (the common block's labels)

 CPU 0

 CLEAR GLUE%, &07C0
 ORG GLUE%
 GUARD &07C0
 INCLUDE "3-assembled-output/gfx-merid-main.asm"
.GLUE_TOP
 SAVE "3-assembled-output/GLUE.bin", GLUE%, GLUE_TOP, GLUE%

 CLEAR &8000, &C000
 ORG C6%                \ the flight code's cold 6 pass (its layout assembles
 INCBIN "3-assembled-output/C6.bin"   \ it: C6.bin, C6SZ bytes)
 ASSERT P% = C6% + C6SZ
.F_START
.FZB    SKIP 16         \ the frame layer's scratch (gfx-frame.asm's fz_*: once
                        \ the zero page's &D2-&E1), first, as the code's
                        \ instructions take it as absolute
.f_fo   SKIP 1          \ f_ship's offset in the face list
.FHV                    \ the hangar's background's ways into this bank (it
 JMP fh_col             \ is in the docked code's main RAM part, assembled
 JMP fh_blk             \ before this: gfx-hangar.asm), at a fixed place
 JMP fh_line
 JMP f_lines
 ASSERT FHV = FHV%

 INCLUDE "3-assembled-output/gfx-frame-bank6.asm"
 INCLUDE "3-assembled-output/gfx-glue-bank6.asm"   \ (the calls out of the bank)
.F_CODEEND
 INCLUDE "1-source-files/main-sources/gfx-faces.asm"
 INCLUDE "1-source-files/main-sources/gfx-light6.asm"
 INCLUDE "1-source-files/main-sources/gfx-font.asm"
IF _ROMCHECK
.rcmap                  \ romcheck=on: the read-only checker's map (gfx-rcheck.asm,
 INCLUDE "1-source-files/main-sources/gfx-rcmap.asm"   \ 6-harness/romap.mjs)
ENDIF
.F_TABEND
 ASSERT P% <= FAR%      \ (the far block, elite-far.asm, and the common block
 SKIP FAR% - P%         \ after it: the code that pages the banks, the same
 INCBIN "3-assembled-output/FAR.bin"      \ bytes in every bank; the far block
 ASSERT P% = COMMON%    \ for the flight code's cold 6 pass, whose far calls
 INCBIN "3-assembled-output/COMMON.bin"   \ run on from one bank's copy into
 ASSERT P% = COMMON_END%                  \ another's)
.F_AL
.F_TM   SKIP 768        \ the text map: desired characters, 24 rows of 32
 ASSERT LO(F_TM) = 0    \ (f_cell adds only the high byte)
.F_TMR  SKIP 24         \ the text map's non-empty cells per row
 ASSERT HI(F_TMR) = HI(F_TMR + 23)   \ (whole in a page: f_text2 reads it every
                        \ frame, by row)
.f_tcol SKIP 1          \ (f_char1's column)
.F_RP   SKIP 29 * MAXSH \ the ship records (F_SHIP): INWK 0-8, XX16, XX0, each
F_SZL = F_RP + 6 * MAXSH  \ a field to an array of MAXSH (the ship's z, INWK
F_SZH = F_RP + 7 * MAXSH  \ 6-7: the sort's)
.f_zsv  SKIP &22        \ F_FRAME's keep of &06-&27
F_SRN = MAXSH * 15      \ (the most faces is 15)
.F_SR   SKIP F_SRN      \ the ships' faces' levels (F_SHIP)
.F_SLV  SKIP 52         \ the docking slot's vertices, as R_PXL .. R_PYH + 3
                        \ (f_poly2, f_slot: gfx-frame_cold.asm; x high of
                        \ vertex 0, F_SLV+16, &80: none)
.f_pph  SKIP 1          \ F_PFHOLD's: bit 7, records were made; the radius,
.f_plr  SKIP 1          \ TYPE, VIEW and MCNT of its last call
.f_plt  SKIP 1
.f_plv  SKIP 1
.f_plm  SKIP 1
.F_SMEND                \ (the end of the state)
 INCLUDE "3-assembled-output/gfx-finit-bank6init.asm"   \ F_INIT (gfx-finit.asm)
                        \ and, in the room after the state, the lens flare's
                        \ call, the screens drawn directly, the hangar and the
                        \ frame layer's set-up (so that the room below the far
                        \ block, for the cold 6 pass, is one piece)
 INCLUDE "3-assembled-output/gfx-flare-bank6.asm"
 INCLUDE "3-assembled-output/gfx-frame_cold-bank6.asm"
 INCLUDE "3-assembled-output/gfx-hangar-bank6.asm"
 INCLUDE "3-assembled-output/gfx-finit-bank6.asm"
IF _ROMCHECK
 INCLUDE "1-source-files/main-sources/gfx-rcheck.asm"   \ romcheck=on: the
ENDIF                                                   \ read-only checker
.F_END
 ASSERT F_END <= FCSLOT \ the face lists of the blueprint set loaded, to FJT
                        \ (FCSLOT and its size: gfx-faces.asm; F_SETLD)

 CLEAR FJT%, &C000      \ (so that an overflow is reported below, with the
 ORG FJT%               \ sizes) the entries, in FG_*'s order (elite-map.asm)
 JMP F_INIT : JMP F_DIRECT : JMP F_FRAME : JMP F_SHIP
 JMP F_LINE : JMP F_PDOT : JMP F_PLANET : JMP F_SHPPT
 JMP F_CHAR : JMP F_DELCHAR : JMP F_CLRTEXT : JMP F_GUN
 JMP F_HANG0 : JMP F_HANGAR : JMP F_CLOUD : JMP F_SETLD
 JMP F_PFHOLD : JMP F_DCHAR
.FJT_TAB
 INCLUDE "3-assembled-output/gfx-glue-bank6entries.asm"   \ (calls out of the bank,
                                                          \ in the room after)
.FJT_END
 ASSERT FJT_TAB - FJT% = 3 * FG_N AND FJT_END <= &C000
 ASSERT HI(FJT%) = HI(FJT_TAB - 1)   \ (GCALL sets only a JSR's low byte: the
                                     \ bank's CBPG, elite-common.asm)


PRINT "Bank 6: the flight code's cold 6 pass ", ~C6%, "-", ~C6% + C6SZ - 1, ", the frame layer's code ", ~F_START, "-", ~F_CODEEND-1, " (", F_CODEEND-F_START, " bytes), tables ", ~F_CODEEND, "-", ~F_TABEND-1, " (", F_TABEND-F_CODEEND, "), free ", FAR%-F_TABEND, ", the far block and the common block ", ~FAR%, "-", ~COMMON_END%-1, ", state ", ~F_AL, "-", ~F_SMEND-1, ", F_INIT to ", ~F_END-1, " (free ", FCSLOT-F_END, "), the face lists' slot ", ~FCSLOT, "-", ~FJT%-1, ", the entries and calls ", ~FJT%, "-", ~FJT_END-1, " (free ", &C000-FJT_END, ")"
PRINT "Glue (main RAM): ", ~GLUE%, "-", ~GLUE_TOP-1, " (pcb_o, ", GLUE_TOP-GLUE%, " bytes)"
 SAVE "3-assembled-output/BANK6.bin", &8000, &C000, &8000
